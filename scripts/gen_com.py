"""Generate retrokit/knowledge/win32/directx.h - the COM interfaces of DirectX 3-9 as plain C
that Ghidra's C parser reads (maintainers only).

    python scripts/gen_com.py HEADER_DIR [-o retrokit/knowledge/win32/directx.h]

HEADER_DIR holds ddraw.h, dsound.h, dinput.h, d3d.h, d3d8.h, d3d9.h, e.g. from MinGW-w64
(mingw-w64-headers/include). Only the interface layouts are taken - interface names, method
names and order, parameter names - which is the binary interface every DirectX program
uses. Parameter types are simplified: pointers to known interfaces stay typed (the kit
propagates them to the variables that receive them), every other pointer becomes void *,
every other scalar a 32-bit integer or float.
"""
import argparse
import os
import re

HEADERS = ["ddraw.h", "dsound.h", "dinput.h", "d3d.h", "d3d8.h", "d3d9.h"]
SCALARS = {
    "DWORD": "DWORD", "ULONG": "ULONG", "LONG": "LONG", "UINT": "UINT", "INT": "int", "int": "int",
    "BOOL": "BOOL", "HRESULT": "HRESULT", "WORD": "WORD", "BYTE": "BYTE", "SHORT": "short",
    "HANDLE": "HANDLE", "HWND": "HWND", "HDC": "HDC", "HINSTANCE": "HINSTANCE", "HMONITOR": "HANDLE",
    "HPALETTE": "HANDLE", "HRGN": "HANDLE", "HMODULE": "HINSTANCE", "HKEY": "HANDLE",
    "float": "float", "FLOAT": "float", "D3DVALUE": "float", "D3DCOLOR": "DWORD", "D3DFORMAT": "DWORD",
    "LPVOID": "void *", "PVOID": "void *", "LPCVOID": "void *", "REFIID": "GUID *", "REFGUID": "GUID *",
    "REFCLSID": "GUID *", "LPGUID": "GUID *", "LPCGUID": "GUID *", "LPCSTR": "char *", "LPSTR": "char *",
    "LPCWSTR": "wchar_t *", "LPWSTR": "wchar_t *", "LPDWORD": "DWORD *", "LPLONG": "LONG *",
    "D3DMATRIXHANDLE": "DWORD", "D3DMATERIALHANDLE": "DWORD", "D3DTEXTUREHANDLE": "DWORD",
    "REFERENCE_TIME": "__int64", "LONGLONG": "__int64", "ULONGLONG": "__int64",
}
PRELUDE = """/* DirectX 3-9 COM interfaces for Ghidra, generated by scripts/gen_com.py: interface and method
 * names and order (the binary interface) with simplified parameter types - pointers to
 * interfaces are typed, other pointers are void *, other scalars 32-bit. retrokit's
 * PropagateComTypes gives these types to the variables the creation functions and methods
 * fill, so calls through the vtables show the method names.
 */

/* basic types (DWORD, GUID, ...) come from 00_types.h, parsed before this file */

typedef struct IUnknown IUnknown;
typedef struct IUnknownVtbl {
    HRESULT (__stdcall *QueryInterface)(IUnknown *This, GUID *riid, void **ppvObject);
    ULONG (__stdcall *AddRef)(IUnknown *This);
    ULONG (__stdcall *Release)(IUnknown *This);
} IUnknownVtbl;
struct IUnknown { IUnknownVtbl *lpVtbl; };
"""

CREATORS = """
/* creation functions (exported by name from the DLLs, __stdcall) */
HRESULT __stdcall DirectDrawCreate(GUID *lpGUID, IDirectDraw **lplpDD, IUnknown *pUnkOuter);
HRESULT __stdcall DirectDrawCreateEx(GUID *lpGuid, IDirectDraw7 **lplpDD, GUID *iid, IUnknown *pUnkOuter);
HRESULT __stdcall DirectDrawCreateClipper(DWORD dwFlags, IDirectDrawClipper **lplpDDClipper, IUnknown *pUnkOuter);
HRESULT __stdcall DirectDrawEnumerateA(void *lpCallback, void *lpContext);
HRESULT __stdcall DirectDrawEnumerateExA(void *lpCallback, void *lpContext, DWORD dwFlags);
HRESULT __stdcall DirectSoundCreate(GUID *pcGuidDevice, IDirectSound **ppDS, IUnknown *pUnkOuter);
HRESULT __stdcall DirectSoundCreate8(GUID *pcGuidDevice, IDirectSound8 **ppDS8, IUnknown *pUnkOuter);
HRESULT __stdcall DirectSoundEnumerateA(void *pDSEnumCallback, void *pContext);
HRESULT __stdcall DirectSoundCaptureCreate(GUID *pcGuidDevice, IDirectSoundCapture **ppDSC, IUnknown *pUnkOuter);
HRESULT __stdcall DirectInputCreateA(HINSTANCE hinst, DWORD dwVersion, IDirectInputA **lplpDirectInput, IUnknown *punkOuter);
HRESULT __stdcall DirectInputCreateW(HINSTANCE hinst, DWORD dwVersion, IDirectInputW **lplpDirectInput, IUnknown *punkOuter);
HRESULT __stdcall DirectInputCreateEx(HINSTANCE hinst, DWORD dwVersion, GUID *riidltf, void **ppvOut, IUnknown *punkOuter);
HRESULT __stdcall DirectInput8Create(HINSTANCE hinst, DWORD dwVersion, GUID *riidltf, IDirectInput8A **ppvOut, IUnknown *punkOuter);
IDirect3D8 * __stdcall Direct3DCreate8(UINT SDKVersion);
IDirect3D9 * __stdcall Direct3DCreate9(UINT SDKVersion);
"""

DECL = re.compile(r"DECLARE_INTERFACE(?:_IID)?_\(\s*(\w+)\s*,\s*(\w+)\s*(?:,\s*\"[^\"]*\")?\s*\)\s*\{(.*?)\n\};", re.S)
METHOD = re.compile(r"STDMETHOD(_\(\s*([^,]+?)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\((.*?)\)\s*PURE\s*;", re.S)
LPTYPEDEF = re.compile(r"typedef\s+struct\s+(\w+)\s+\*\s*(\w+)\s*(?:,\s*\*\s*\*\s*(\w+))?\s*;")


def norm_type(t, aliases, interfaces):
    """C type of one parameter / return value"""
    t = re.sub(r"\b(const|CONST|FAR|IN|OUT|OPTIONAL|struct|__RPC_FAR)\b", " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    stars = t.count("*")
    base = t.replace("*", "").strip()
    if base in aliases:                     # LPDIRECTDRAWSURFACE7 -> IDirectDrawSurface7 *
        iface, extra = aliases[base]
        return iface + " " + "*" * (extra + stars)
    if base in interfaces:
        return base + " " + "*" * stars if stars else "void *"
    if base in ("void", "VOID") and stars:
        return "void " + "*" * stars
    if base in SCALARS:
        s = SCALARS[base]
        return s + (" " + "*" * stars if stars else "") if not s.endswith("*") else s + "*" * stars
    if stars or base.startswith(("LP", "P")) and base[1:2].isupper():
        return "void *"
    return "DWORD"                         # enums, flags, handles of other kinds


def parse(paths):
    interfaces, aliases, order = {"IUnknown": "builtin"}, {"LPUNKNOWN": ("IUnknown", 1)}, []
    texts = []
    for p in paths:
        with open(p, encoding="utf-8", errors="replace") as fh:
            texts.append(fh.read())
    text = "\n".join(texts)
    for m in DECL.finditer(text):
        interfaces.setdefault(m.group(1), None)
    for m in LPTYPEDEF.finditer(text):
        if m.group(1) in interfaces:
            aliases[m.group(2)] = (m.group(1), 1)
            if m.group(3):
                aliases[m.group(3)] = (m.group(1), 2)
    for m in DECL.finditer(text):
        name, base, body = m.group(1), m.group(2), m.group(3)
        if interfaces.get(name) or name == "IUnknown":
            continue                        # the first declaration wins (A/W duplicates)
        methods = []
        for mm in METHOD.finditer(body):
            ret = mm.group(2) or "HRESULT"
            mname = mm.group(3) or mm.group(4)
            params = re.sub(r"\s+", " ", mm.group(5)).strip()
            params = re.sub(r"^THIS_?\s*", "", params).strip()
            plist = []
            for i, prm in enumerate([x.strip() for x in params.split(",") if x.strip()]):
                pm = re.match(r"^(.*?)(\w+)(\s*\[\s*\w*\s*\])?$", prm)
                if pm and pm.group(1).strip():
                    ptype, pname = pm.group(1), pm.group(2)
                    if pm.group(3):
                        ptype += "*"
                else:
                    ptype, pname = prm, "p%d" % (i + 1)
                plist.append((norm_type(ptype, aliases, interfaces), pname))
            methods.append((norm_type(ret, aliases, interfaces), mname, plist))
        if methods:
            interfaces[name] = (base, methods)
            order.append(name)
    return interfaces, order


def emit(interfaces, order, out):
    lines = [PRELUDE]
    for name in order:
        lines.append("typedef struct %s %s;" % (name, name))
    for name in order:
        base, methods = interfaces[name]
        lines.append("")
        lines.append("typedef struct %sVtbl {" % name)
        seen = set()
        for ret, mname, params in methods:
            field = mname if mname not in seen else "%s_%d" % (mname, len(seen))
            seen.add(mname)
            args = ", ".join(["%s *This" % name] + ["%s %s" % p for p in params])
            lines.append("    %s (__stdcall *%s)(%s);" % (ret, field, args))
        lines.append("} %sVtbl;" % name)
        lines.append("struct %s { %sVtbl *lpVtbl; };" % (name, name))
    lines.append(CREATORS)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    return sum(len(interfaces[n][1]) for n in order)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("header_dir")
    ap.add_argument("-o", "--out", default=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                                       "retrokit", "knowledge", "win32", "directx.h"))
    a = ap.parse_args()
    paths = [os.path.join(a.header_dir, h) for h in HEADERS if os.path.exists(os.path.join(a.header_dir, h))]
    interfaces, order = parse(paths)
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    n = emit(interfaces, order, a.out)
    print("%d interfaces, %d methods -> %s" % (len(order), n, a.out))


if __name__ == "__main__":
    main()
